// Entity model -> the generated CSDL XML file and the storage mapping (where every entity set lives in the database).
import type { GenEntity, GenModel } from './model';

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const attrs = (o: Record<string, string | number | boolean | undefined>) =>
  Object.entries(o)
    .filter(([, v]) => v !== undefined)
    .map(([k, v]) => ` ${k}="${esc(String(v))}"`)
    .join('');

function entityType(ns: string, e: GenEntity): string {
  const lines = [`      <EntityType Name="${esc(e.type)}">`, `        <Key>${e.keys.map((k) => `<PropertyRef Name="${esc(k)}"/>`).join('')}</Key>`];
  for (const p of e.properties) {
    lines.push(`        <Property${attrs({ Name: p.name, Type: p.edmType, Nullable: p.nullable ? undefined : false, MaxLength: p.maxLength, Precision: p.precision, Scale: p.scale })}/>`);
  }
  for (const n of e.navigations) {
    const type = n.collection ? `Collection(${ns}.${n.targetType})` : `${ns}.${n.targetType}`;
    const open = `        <NavigationProperty${attrs({ Name: n.name, Type: type, Nullable: n.collection || n.nullable ? undefined : false, Partner: n.partner })}`;
    if (!n.constraints?.length) lines.push(`${open}/>`);
    else {
      lines.push(`${open}>`);
      for (const c of n.constraints) lines.push(`          <ReferentialConstraint${attrs({ Property: c.property, ReferencedProperty: c.referencedProperty })}/>`);
      lines.push('        </NavigationProperty>');
    }
  }
  lines.push('      </EntityType>');
  return lines.join('\n');
}

/** The generated CSDL document. Deterministic (same database, same file), so that diffs show real changes. */
export function toCsdl(m: GenModel, source: string): string {
  const ns = m.namespace;
  const out: string[] = [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- Generated by smart-kit-cli from ${source.replace(/--/g, '- -')}. Do not edit: run "smart-kit generate" again. Annotations belong in the hand-written annotation file. -->`,
    '<edmx:Edmx Version="4.0" xmlns:edmx="http://docs.oasis-open.org/odata/ns/edmx">',
    '  <edmx:Reference Uri="https://sap.github.io/odata-vocabularies/vocabularies/Common.xml">',
    '    <edmx:Include Namespace="com.sap.vocabularies.Common.v1" Alias="Common"/>',
    '  </edmx:Reference>',
    '  <edmx:Reference Uri="https://oasis-tcs.github.io/odata-vocabularies/vocabularies/Org.OData.Core.V1.xml">',
    '    <edmx:Include Namespace="Org.OData.Core.V1" Alias="Core"/>',
    '  </edmx:Reference>',
    '  <edmx:DataServices>',
    `    <Schema Namespace="${esc(ns)}" xmlns="http://docs.oasis-open.org/odata/ns/edm">`,
  ];
  for (const e of m.entities) out.push(entityType(ns, e));
  out.push(`      <EntityContainer Name="${esc(m.container)}">`);
  for (const e of m.entities) {
    const bindings = e.navigations.map((n) => `          <NavigationPropertyBinding${attrs({ Path: n.name, Target: n.targetSet })}/>`);
    if (!bindings.length) out.push(`        <EntitySet${attrs({ Name: e.set, EntityType: `${ns}.${e.type}` })}/>`);
    else out.push(`        <EntitySet${attrs({ Name: e.set, EntityType: `${ns}.${e.type}` })}>`, ...bindings, '        </EntitySet>');
  }
  out.push('      </EntityContainer>');
  for (const e of m.entities) {
    if (e.description) out.push(`      <Annotations Target="${esc(`${ns}.${e.type}`)}"><Annotation Term="Core.Description"${attrs({ String: e.description })}/></Annotations>`);
    for (const p of e.properties) {
      const terms = [
        ...(p.label ? [`<Annotation Term="Common.Label"${attrs({ String: p.label })}/>`] : []),
        ...(p.computed ? ['<Annotation Term="Core.Computed" Bool="true"/>'] : []),
      ];
      if (terms.length) out.push(`      <Annotations Target="${esc(`${ns}.${e.type}/${p.name}`)}">${terms.join('')}</Annotations>`);
    }
  }
  out.push('    </Schema>', '  </edmx:DataServices>', '</edmx:Edmx>', '');
  return out.join('\n');
}

/** The storage mapping read by smart-kit-server: entity set -> table, property -> column. */
export function toStorage(m: GenModel) {
  return {
    $comment: 'Generated by smart-kit-cli. Do not edit: run "smart-kit generate" again.',
    entitySets: Object.fromEntries(
      m.entities.map((e) => {
        const declared = e.navigations.filter((n) => n.on);
        const columns = Object.fromEntries(e.properties.map((p) => [p.name, p.column]));
        // joins of the declared navigations: $metadata has no referential constraints for a collection navigation
        if (!declared.length) return [e.set, { table: `${e.schema}.${e.table}`, columns }];
        return [e.set, { table: `${e.schema}.${e.table}`, columns, navigations: Object.fromEntries(declared.map((n) => [n.name, { on: n.on }])) }];
      }),
    ),
  };
}
