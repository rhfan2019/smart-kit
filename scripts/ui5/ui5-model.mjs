// Reads one SAPUI5 class, namespace or enum out of api.json into the shape the comparison uses (docs/30 §7.1).

/** Base classes whose members are not compared: the generic control / element / building-block machinery (ADR-032 rule 4). */
export const BASE_CLASSES = new Set([
  'sap.ui.core.Control', 'sap.ui.core.Element', 'sap.ui.base.ManagedObject', 'sap.ui.base.EventProvider', 'sap.ui.base.Object',
  'sap.fe.core.buildingBlocks.BuildingBlock', 'sap.fe.base.BuildingBlockBase', 'sap.fe.macros.controls.BuildingBlockObjectProperty',
  'sap.ui.core.UIComponent', 'sap.ui.core.Component', 'sap.ui.core.mvc.Controller', 'sap.ui.core.mvc.ControllerExtension',
]);

/**
 * Accessors generated by ManagedObject for properties, aggregations, associations and events (getText, addItem,
 * attachPress…; docs/30 §7.1 step 4): api.json lists them in each member's `methods`. Other get/set methods
 * (Wizard.getProgress, ProcessFlow.setZoomLevel) are real API and are compared.
 */
function generatedAccessors(md) {
  const out = new Set();
  for (const group of ['properties', 'aggregations', 'associations', 'events']) for (const m of md[group] ?? []) for (const n of m.methods ?? []) out.add(n);
  return out;
}
const OBJECT_METHODS = new Set(['extend', 'getMetadata', 'init', 'exit', 'onBeforeRendering', 'onAfterRendering', 'clone', 'applySettings']);

const isPublic = (m) => (m.visibility ?? 'public') === 'public' && !m.deprecated;

function strip(value) {
  if (value === undefined || value === null) return undefined;
  if (typeof value !== 'string') return value;
  // enum defaults are written as "sap.m.ButtonType.Default"; compare the value only
  const m = /^sap\.[\w.]+\.([A-Z]\w*)\.(\w+)$/.exec(value);
  return m ? m[2] : value;
}

/** Describes a UI5 symbol, merging the members of its non-base ancestors. Returns undefined for an unknown name. */
export function describeUi5(name, symbols) {
  const sym = symbols.get(name);
  if (!sym) return undefined;
  const out = {
    name, kind: sym.kind, module: sym.module, basename: sym.basename, library: sym.library, deprecated: Boolean(sym.deprecated),
    properties: [], aggregations: [], associations: [], events: [], methods: [], staticMembers: [], enumValues: [],
    defaultAggregation: undefined, ancestors: [], unresolvedAncestor: undefined,
  };
  if (sym.kind === 'enum') {
    out.enumValues = (sym.properties ?? []).filter(isPublic).map((p) => p.name);
    return out;
  }
  const seen = new Set();
  const chain = [];
  for (let cur = sym; cur; ) {
    chain.push(cur);
    const parent = cur.extends;
    if (!parent || BASE_CLASSES.has(parent)) break;
    const next = symbols.get(parent);
    if (!next) { out.unresolvedAncestor = parent; break; }
    out.ancestors.push(parent);
    cur = next;
  }
  // methods a class re-declares from its base classes (getDomRef, setTooltip, addStyleClass, setModel…) are base API
  const baseMethods = new Set();
  for (const b of BASE_CLASSES) for (const m of symbols.get(b)?.methods ?? []) baseMethods.add(m.name);
  const generated = new Set(baseMethods);
  for (const s of chain) for (const n of generatedAccessors(s['ui5-metadata'] ?? {})) generated.add(n);
  for (const s of chain) {
    const md = s['ui5-metadata'] ?? {};
    if (!out.defaultAggregation && md.defaultAggregation) out.defaultAggregation = md.defaultAggregation;
    for (const p of md.properties ?? []) if (isPublic(p) && !seen.has('p:' + p.name)) {
      seen.add('p:' + p.name);
      out.properties.push({ name: p.name, type: p.type, defaultValue: strip(p.defaultValue), owner: s.name });
    }
    for (const a of md.aggregations ?? []) if (isPublic(a) && !seen.has('a:' + a.name)) {
      seen.add('a:' + a.name);
      out.aggregations.push({ name: a.name, type: a.type, multiple: a.cardinality === '0..n', owner: s.name });
    }
    for (const a of md.associations ?? []) if (isPublic(a) && !seen.has('s:' + a.name)) {
      seen.add('s:' + a.name);
      out.associations.push({ name: a.name, type: a.type, owner: s.name });
    }
    for (const e of md.events ?? []) if (isPublic(e) && !seen.has('e:' + e.name)) {
      seen.add('e:' + e.name);
      const params = Object.entries(e.parameters ?? {}).filter(([, v]) => !v?.deprecated).map(([k]) => k);
      out.events.push({ name: e.name, params, allowPreventDefault: Boolean(e.allowPreventDefault), owner: s.name });
    }
    for (const m of s.methods ?? []) {
      if (!isPublic(m) || OBJECT_METHODS.has(m.name)) continue;
      if (!m.static && generated.has(m.name)) continue;
      // static methods belong to the class itself, not to its ancestors
      if (m.static && s !== sym) continue;
      const key = (m.static ? 'S:' : 'm:') + m.name;
      if (seen.has(key)) continue;
      seen.add(key);
      out.methods.push({ name: m.name, static: Boolean(m.static) || sym.kind === 'namespace', params: (m.parameters ?? []).map((p) => p.name), owner: s.name });
    }
  }
  // enums and classes nested in a namespace or class (sap.m.MessageBox.Action) are static members
  for (const [n, s] of symbols) {
    if (n.startsWith(name + '.') && !n.slice(name.length + 1).includes('.') && (s.kind === 'enum') && isPublic(s)) out.staticMembers.push(s.basename ?? n.slice(name.length + 1));
  }
  return out;
}
