// `smart-kit agents`: points coding agents (Codex, Claude Code, Cursor, …) at the docs that ship inside the installed
// smart-kit packages (ADR-030). Writes a marked block into AGENTS.md (read by Codex and most agents) and makes sure
// CLAUDE.md imports AGENTS.md (Claude Code reads CLAUDE.md, `@AGENTS.md` pulls the file in). Re-running replaces the
// block, so it follows package upgrades; nothing outside the markers is touched.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const BEGIN = '<!-- smart-kit:begin (generated by `smart-kit agents`, do not edit inside) -->';
const END = '<!-- smart-kit:end -->';
const SCOPE = '@rhfan2019';
const PACKAGES = ['smart-kit', 'smart-kit-core', 'smart-kit-server', 'smart-kit-cli'];

export interface AgentsResult {
  /** Files written (AGENTS.md always, CLAUDE.md when created or changed). */
  written: string[];
  /** Installed smart-kit packages found under node_modules, with their versions. */
  packages: { name: string; version: string }[];
}

const md = (dir: string): string[] =>
  existsSync(dir) ? readdirSync(dir, { recursive: true }).map(String).filter((f) => f.endsWith('.md') && statSync(join(dir, f)).isFile()).sort() : [];

/** The block that goes between the markers, built from what is installed under `<cwd>/node_modules`. */
export function agentsBlock(cwd: string): { text: string; packages: AgentsResult['packages'] } {
  const found: AgentsResult['packages'] = [];
  const lines: string[] = [];
  for (const short of PACKAGES) {
    const dir = join(cwd, 'node_modules', SCOPE, short);
    if (!existsSync(join(dir, 'package.json'))) continue;
    const { name, version } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')) as { name: string; version: string };
    found.push({ name, version });
    const rel = relative(cwd, dir).split('\\').join('/');
    const docs = md(join(dir, 'docs')).map((f) => `docs/${f.split('\\').join('/')}`);
    const skills = md(join(dir, 'skills')).filter((f) => f.endsWith('SKILL.md')).map((f) => `skills/${f.split('\\').join('/')}`);
    if (!docs.length && !skills.length) continue;
    lines.push(`- \`${name}@${version}\`: ${[...docs, ...skills].map((f) => `\`${rel}/${f}\``).join(', ')}`);
  }
  const text = [
    BEGIN,
    '## smart-kit',
    '',
    'This project uses smart-kit (metadata-driven React list / object pages on OData V4, and an OData V4 server on PostgreSQL).',
    'Your training data does not know its API. **Before writing or changing code that uses smart-kit, read the docs that ship',
    'with the installed version** — start with the `docs/README.md` of each package below. Prefer them over guesses and over',
    'other UI libraries\' conventions. For a new project or a new entity, follow the skill',
    '`node_modules/@rhfan2019/smart-kit/skills/smart-kit-getting-started/SKILL.md` (in `@rhfan2019/smart-kit`).',
    '',
    ...(lines.length ? lines : ['- (no smart-kit package with docs found in node_modules — run `npm install` first, then `npx smart-kit agents` again)']),
    END,
  ].join('\n');
  return { text, packages: found };
}

/** Writes or refreshes the smart-kit block in `<cwd>/AGENTS.md` and the `@AGENTS.md` import in `<cwd>/CLAUDE.md`. */
export function agents(cwd = process.cwd()): AgentsResult {
  const { text, packages } = agentsBlock(cwd);
  const written: string[] = [];
  const agentsPath = join(cwd, 'AGENTS.md');
  const before = existsSync(agentsPath) ? readFileSync(agentsPath, 'utf8') : '';
  const start = before.indexOf(BEGIN);
  const end = before.indexOf(END);
  const after =
    start >= 0 && end > start
      ? before.slice(0, start) + text + before.slice(end + END.length)
      : before.trim()
        ? `${before.trimEnd()}\n\n${text}\n`
        : `# AGENTS.md\n\n${text}\n`;
  if (after !== before) writeFileSync(agentsPath, after);
  written.push(agentsPath);
  const claudePath = join(cwd, 'CLAUDE.md');
  const claude = existsSync(claudePath) ? readFileSync(claudePath, 'utf8') : '';
  if (!/^@AGENTS\.md\s*$/m.test(claude)) {
    writeFileSync(claudePath, claude.trim() ? `${claude.trimEnd()}\n\n@AGENTS.md\n` : '@AGENTS.md\n');
    written.push(claudePath);
  }
  return { written, packages };
}
